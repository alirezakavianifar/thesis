#!/usr/bin/env python3
"""
LaTeX Build Artifact Cleanup Utility for Doctoral Dissertation Repository.

Removes auxiliary and intermediate files generated by XeLaTeX, BibTeX, and MakeIndex
(.aux, .log, .out, .toc, .lof, .lot, .fls, .fdb_latexmk, .synctex.gz, .bbl, .blg,
 .bcf, .run.xml, .idx, .ilg, .ind, .nav, .snm, .vrb, .xdv, .dvi, texput.log),
while strictly preserving source files (.tex, .bib, .cls, .sty, images) and the compiled PDF.
"""

import os
import sys
import argparse
from pathlib import Path

# Standard auxiliary extensions to purge
AUX_EXTENSIONS = {
    '.aux', '.log', '.out', '.toc', '.lof', '.lot',
    '.fls', '.fdb_latexmk', '.synctex.gz', '.bbl', '.blg',
    '.bcf', '.run.xml', '.idx', '.ilg', '.ind',
    '.nav', '.snm', '.vrb', '.xdv', '.dvi', '.ps'
}

EXACT_FILENAMES = {
    'texput.log', 'thesis_full_toc_persian_v3.idx'
}

def clean_build_artifacts(root_dir: Path, dry_run: bool = False, include_pdf: bool = False) -> tuple[int, int]:
    """
    Scans root_dir and subdirectories for LaTeX build artifacts and removes them.
    Returns (count_deleted, bytes_freed).
    """
    deleted_count = 0
    bytes_freed = 0

    # Scan root directory and chapters directory
    search_dirs = [root_dir]
    chapters_dir = root_dir / 'chapters'
    if chapters_dir.is_dir():
        search_dirs.append(chapters_dir)

    for directory in search_dirs:
        for item in directory.iterdir():
            if not item.is_file():
                continue

            should_delete = False

            if item.suffix.lower() in AUX_EXTENSIONS:
                should_delete = True
            elif item.name in EXACT_FILENAMES:
                should_delete = True
            elif include_pdf and item.suffix.lower() == '.pdf':
                should_delete = True

            # Safety check: Never delete source files or persistent caches
            if item.suffix.lower() in {'.tex', '.bib', '.cls', '.sty', '.png', '.jpg', '.pdf'}:
                if not (include_pdf and item.suffix.lower() == '.pdf'):
                    should_delete = False
            elif item.name.lower() in {'master_labels.aux', 'master.bbl'}:
                should_delete = False

            if should_delete:
                file_size = item.stat().st_size
                if not dry_run:
                    try:
                        item.unlink()
                        deleted_count += 1
                        bytes_freed += file_size
                        print(f"  [DELETED] {item.relative_to(root_dir)} ({file_size / 1024:.1f} KB)")
                    except Exception as e:
                        print(f"  [ERROR] Could not delete {item.relative_to(root_dir)}: {e}", file=sys.stderr)
                else:
                    deleted_count += 1
                    bytes_freed += file_size
                    print(f"  [DRY-RUN] Would delete {item.relative_to(root_dir)} ({file_size / 1024:.1f} KB)")

    return deleted_count, bytes_freed

def main():
    parser = argparse.ArgumentParser(description="Clean LaTeX build artifacts.")
    parser.add_argument("--dry-run", action="store_true", help="Simulate deletion without removing files.")
    parser.add_argument("--include-pdf", action="store_true", help="Also remove generated .pdf files.")
    parser.add_argument("--dir", default=".", help="Root directory of the thesis repository.")
    args = parser.parse_args()

    root_path = Path(args.dir).resolve()
    print("=" * 60)
    print("        LATEX BUILD ARTIFACT CLEANUP UTILITY")
    print("=" * 60)
    print(f"Target Directory: {root_path}")
    print(f"Mode: {'DRY RUN' if args.dry_run else 'ACTIVE CLEANUP'}")
    print(f"Include PDF: {'YES' if args.include_pdf else 'NO (Preserving PDF)'}")
    print("-" * 60)

    count, bytes_freed = clean_build_artifacts(root_path, dry_run=args.dry_run, include_pdf=args.include_pdf)

    print("-" * 60)
    if count == 0:
        print("[CLEAN] Workspace is already pristine. No build artifacts found.")
    else:
        status_word = "Would free" if args.dry_run else "Successfully freed"
        print(f"[DONE] Processed {count} file(s). {status_word} {bytes_freed / 1024:.1f} KB.")
    print("=" * 60)

if __name__ == "__main__":
    main()

