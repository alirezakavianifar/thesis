#!/usr/bin/env python3
r"""
Synchronizes a standalone chapter's .bbl file with master dissertation citation numbers.

1. Reads cited keys from chapter_name.aux (\citation{key}).
2. Reads master citation numbers from master.bbl or master_labels.aux.
3. Extracts matching \bibitem entries from master.bbl.
4. Formats each entry as \bibitem[N]{key} with Persian digits so that in-text
   citations and the chapter bibliography list use the authentic master thesis
   numbers (e.g. [۲۸]).
5. Writes the filtered bibliography into chapter_name.bbl.
"""

import sys
import re
import shutil
from pathlib import Path

def to_persian_digits(s: str) -> str:
    tr = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")
    return str(s).translate(tr)

def sync_bib(chapter_base: str, root_dir: str = ".", master_bbl_name: str = "master.bbl") -> int:
    root = Path(root_dir).resolve()
    chap_aux = root / f"{chapter_base}.aux"
    chap_bbl = root / f"{chapter_base}.bbl"
    master_bbl = root / master_bbl_name
    master_aux = root / "master_labels.aux"

    if not master_bbl.exists():
        # Check if thesis_full_toc_persian_v3.bbl exists
        full_bbl = root / "thesis_full_toc_persian_v3.bbl"
        if full_bbl.exists():
            shutil.copy(full_bbl, master_bbl)
        else:
            print(f"[WARN] {master_bbl_name} not found. Cannot sync master citations.")
            return 1

    if not chap_aux.exists():
        print(f"[ERROR] {chap_aux.name} not found. Run XeLaTeX pass 1 before syncing bibliography.")
        return 1

    # 1. Read cited keys in order of appearance
    with open(chap_aux, "r", encoding="utf-8", errors="ignore") as f:
        aux_content = f.read()

    raw_cites = re.findall(r"\\citation\{(.*?)\}", aux_content)
    cited_keys = []
    seen = set()
    for c in raw_cites:
        for key in c.split(","):
            key = key.strip()
            if key and key not in seen:
                seen.add(key)
                cited_keys.append(key)

    if not cited_keys:
        print(f"[INFO] No citations found in {chap_aux.name}.")
        return 0

    print(f"[INFO] Found {len(cited_keys)} unique citation(s) in {chap_aux.name}.")

    # 2. Parse master.bbl entries
    with open(master_bbl, "r", encoding="utf-8", errors="ignore") as f:
        master_text = f.read()

    # Match each entry including any enclosing LTRbibitems environment
    pattern = re.compile(
        r"((?:\\begin\{LTRbibitems\}\s*(?:\\resetlatinfont\s*)?)?\\bibitem(?:\[[^\]]*\])?\{([^}]+)\}.*?(?:\\end\{LTRbibitems\}|(?=\\begin\{LTRbibitems\}|\\bibitem|\\end\{thebibliography\}|\Z)))",
        re.DOTALL
    )
    master_entries = {}
    for idx, match in enumerate(pattern.finditer(master_text), 1):
        full_block = match.group(1).strip()
        key = match.group(2).strip()
        master_entries[key] = (idx, full_block)

    # Check if master_labels.aux has explicit \bibcite numbers
    bibcite_map = {}
    if master_aux.exists():
        with open(master_aux, "r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                m = re.match(r"\\bibcite\{([^}]+)\}\{([^}]+)\}", line.strip())
                if m:
                    bibcite_map[m.group(1)] = m.group(2)

    # 3. Build chapter.bbl sorted by master citation number
    sorted_keys = sorted(
        cited_keys,
        key=lambda k: int(bibcite_map.get(k, master_entries.get(k, (9999, ""))[0]))
    )

    out_lines = [
        "% Generated by sync_chapter_bib.py for standalone chapter compilation\n",
        "\\providecommand{\\noopsort}[1]{}\n",
        "\\begin{thebibliography}{99}\n\n"
    ]
    found_count = 0
    for key in sorted_keys:
        if key in master_entries:
            default_idx, block = master_entries[key]
            # Resolve master number
            num = str(bibcite_map.get(key, default_idx))

            # Replace \bibitem to have explicit master index [num]
            new_block = re.sub(
                r"\\bibitem(?:\[[^\]]*\])?\{" + re.escape(key) + r"\}",
                f"\\\\bibitem[{num}]{{{key}}}",
                block,
                count=1
            )
            out_lines.append(new_block + "\n\n")
            found_count += 1
        else:
            print(f"  [WARN] Citation key `{key}` not found in master bibliography.")

    out_lines.append("\\end{thebibliography}\n")

    with open(chap_bbl, "w", encoding="utf-8") as f:
        f.writelines(out_lines)

    print(f"[SUCCESS] Wrote {found_count} citation(s) with master numbering into {chap_bbl.name}.")
    return 0

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python sync_chapter_bib.py <chapter_basename> [root_dir]")
        sys.exit(1)
    base = sys.argv[1]
    r_dir = sys.argv[2] if len(sys.argv) > 2 else "."
    sys.exit(sync_bib(base, root_dir=r_dir))
